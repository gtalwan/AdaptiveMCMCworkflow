#' AdaptiveMCMCWorkflow: Teaching Adaptive MCMC Slowly and Explicitly
#'
#' `AdaptiveMCMCWorkflow` is a teaching package for adaptive random-walk MCMC.
#' The computational kernels live in C++ via `RcppArmadillo`, while the target
#' distributions, summaries, plots, and diagnostics live in R.
#'
#' The package focuses on four algorithms:
#'
#' - basic Metropolis
#' - Adaptive Metropolis (AM)
#' - Robust Adaptive Metropolis (RAM)
#' - Delayed Rejection Adaptive Metropolis (DRAM)
#'
#' The package is built around a small set of sampler wrappers, target
#' constructors, summary helpers, and plotting helpers. In this source repo,
#' the simplest end-to-end demonstration is the script `run_adaptive_mcmc_demo.R`.
#'
#' The package does not claim to prove general adaptive MCMC validity from
#' simulation. Instead, it provides empirical diagnostics that help a learner
#' think about ideas such as diminishing adaptation and containment.
#'
#' @keywords internal
#' @useDynLib AdaptiveMCMCWorkflow, .registration = TRUE
#' @importFrom Rcpp evalCpp
"_PACKAGE"

#' Low-level Compiled Samplers
#'
#' These are the direct R wrappers generated by `Rcpp::compileAttributes()`.
