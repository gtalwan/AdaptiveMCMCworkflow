#' Run the Full Teaching Suite
#'
#' This helper runs the four teaching samplers on the same target using one
#' consistent set of controls.
#'
#' @param target A target object created by one of the package target
#'   constructors.
#' @param n_iter Number of iterations used for each sampler.
#' @param initial_state Optional common starting point shared by all samplers.
#' @param controls Optional named list used to override sampler defaults. The
#'   top-level names should be `basic`, `adaptive`, `ram`, and `dram`.
#' @param seed Optional random seed set once before the suite run.
#'
#' @return An object of class `"adaptive_mcmc_comparison"`.
#'
#' @examples
#' comparison <- run_sampler_suite(make_correlated_t_target(), n_iter = 300, seed = 1)
#' names(comparison$runs)
#'
#' @export
run_sampler_suite <- function(target,
                              n_iter = 2000L,
                              initial_state = NULL,
                              controls = NULL,
                              seed = NULL) {
  target <- validate_target(target)
  n_iter <- ensure_positive_integer(n_iter, "n_iter")
  initial_state <- initial_state %||% target$recommended_initial %||% rep(0, target$dimension)
  initial_state <- ensure_numeric_state(initial_state)

  if (length(initial_state) != target$dimension) {
    stop("`initial_state` must match the target dimension.", call. = FALSE)
  }

  if (!is.null(seed)) {
    set.seed(as.integer(seed))
  }

  controls <- merge_sampler_controls(default_sampler_controls(target), controls)

  runs <- list(
    basic = basic_metropolis(
      target_density = target$density,
      initial_state = initial_state,
      n_iter = n_iter,
      proposal_covariance = controls$basic$proposal_covariance
    ),
    adaptive = adaptive_metropolis(
      target_density = target$density,
      initial_state = initial_state,
      n_iter = n_iter,
      initial_proposal_covariance = controls$adaptive$initial_proposal_covariance,
      adapt_start = controls$adaptive$adapt_start,
      epsilon = controls$adaptive$epsilon
    ),
    ram = robust_adaptive_metropolis(
      target_density = target$density,
      initial_state = initial_state,
      n_iter = n_iter,
      initial_proposal_covariance = controls$ram$initial_proposal_covariance,
      target_acceptance = controls$ram$target_acceptance,
      adapt_exponent = controls$ram$adapt_exponent
    ),
    dram = dram(
      target_density = target$density,
      initial_state = initial_state,
      n_iter = n_iter,
      initial_proposal_covariance = controls$dram$initial_proposal_covariance,
      adapt_start = controls$dram$adapt_start,
      delayed_rejection_scale = controls$dram$delayed_rejection_scale,
      epsilon = controls$dram$epsilon
    )
  )

  for (name in names(runs)) {
    runs[[name]]$target_name <- target$name
  }

  structure(
    list(
      target = target,
      initial_state = initial_state,
      n_iter = n_iter,
      controls = controls,
      runs = runs
    ),
    class = "adaptive_mcmc_comparison"
  )
}

#' Compare Adaptive Methods
#'
#' This high-level helper runs the four main samplers on one target, summarizes
#' them, and optionally times them.
#'
#' @param target A target object created by one of the package target
#'   constructors.
#' @param n_iter Number of iterations run for each sampler.
#' @param burn_in Number of initial iterations dropped before summaries are
#'   computed.
#' @param controls Optional named list of sampler-specific settings merged into
#'   the defaults.
#' @param seed Optional seed used before the comparison.
#' @param benchmark Logical. Should the function also time the samplers?
#' @param benchmark_repetitions Number of timing repetitions when
#'   `benchmark = TRUE`.
#'
#' @return A list with elements `comparison`, `summary`, and optionally
#'   `benchmark`. The object also has class `"adaptive_method_comparison"`.
#'
#' @examples
#' results <- compare_adaptive_methods(
#'   target = make_correlated_t_target(),
#'   n_iter = 250,
#'   burn_in = 50,
#'   seed = 1,
#'   benchmark = FALSE
#' )
#' results$summary
#'
#' @export
compare_adaptive_methods <- function(target,
                                     n_iter = 2000L,
                                     burn_in = 0L,
                                     controls = NULL,
                                     seed = NULL,
                                     benchmark = TRUE,
                                     benchmark_repetitions = 3L) {
  comparison <- run_sampler_suite(
    target = target,
    n_iter = n_iter,
    controls = controls,
    seed = seed
  )

  result <- list(
    comparison = comparison,
    summary = summarize_sampler_suite(comparison, burn_in = burn_in)
  )

  if (isTRUE(benchmark)) {
    result$benchmark <- benchmark_sampler_suite(
      target = target,
      n_iter = n_iter,
      repetitions = benchmark_repetitions,
      controls = controls,
      seed = seed
    )
  }

  class(result) <- c("adaptive_method_comparison", "list")
  result
}
