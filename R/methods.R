#' [robust_adaptive_metropolis()], and [dram()].
#'
#' @name compiled_samplers
#' @aliases basic_metropolis_cpp adaptive_metropolis_cpp
#'   robust_adaptive_metropolis_cpp dram_cpp
#' @keywords internal
