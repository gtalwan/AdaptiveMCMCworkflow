#' Run Basic Metropolis
#'
#' This is the fixed-kernel random-walk Metropolis baseline. The R wrapper
#' checks the inputs, calls `basic_metropolis_cpp()`, and then adds the common
#' package metadata used by the plotting and summary helpers.
#'
#' @param target_density Function of one numeric state vector `x` that returns
#'   the target density `pi(x)`.
#' @param log_target Deprecated compatibility alias. If supplied, the wrapper
#'   converts `log_target(x)` to `exp(log_target(x))`.
#' @param initial_state Numeric vector giving the starting value of the chain.
#' @param n_iter Number of Metropolis updates to run.
#' @param proposal_covariance Covariance matrix `S` in the Gaussian random-walk
#'   proposal `x^* = x + N(0, S)`.
#'
#' @return An object of class `"adaptive_mcmc_run"`.
#'
#' @examples
#' target <- make_correlated_gaussian_target()
#' run <- basic_metropolis(
#'   target_density = target$density,
#'   initial_state = target$recommended_initial,
#'   n_iter = 200,
#'   proposal_covariance = diag(2)
#' )
#' head(run$draws)
#'
#' @export
basic_metropolis <- function(target_density = NULL,
                             initial_state,
                             n_iter,
                             proposal_covariance = diag(length(initial_state)),
                             log_target = NULL) {
  # Validate the R inputs before calling the compiled sampler.
  target_density <- resolve_target_density(target_density, log_target)
  initial_state <- ensure_numeric_state(initial_state)
  n_iter <- ensure_positive_integer(n_iter, "n_iter")
  proposal_covariance <- ensure_square_matrix(
    proposal_covariance,
    length(initial_state),
    "proposal_covariance"
  )

  check_initial_density(target_density, initial_state)

  # Call the compiled implementation in src/basic_metropolis.cpp.
  result <- basic_metropolis_cpp(
    target_density = target_density,
    initial_state = initial_state,
    n_iter = n_iter,
    proposal_covariance = proposal_covariance
  )

  # Add the standard class and metadata expected by the R tools.
  standardise_sampler_output(result, initial_state = initial_state)
}

#' Run Adaptive Metropolis
#'
#' Adaptive Metropolis (AM) begins with a fixed pilot covariance and then learns
#' an empirical covariance from the realised chain. The R wrapper checks the
#' inputs, calls `adaptive_metropolis_cpp()`, and returns the result in the
#' standard package format.
#'
#' @param target_density Function of one numeric state vector `x` that returns
#'   the target density `pi(x)`.
#' @param log_target Deprecated compatibility alias. If supplied, the wrapper
#'   converts `log_target(x)` to `exp(log_target(x))`.
#' @param initial_state Numeric vector giving the starting value of the chain.
#' @param n_iter Number of Metropolis updates to run.
#' @param initial_proposal_covariance Initial covariance matrix `S_0` used
#'   before AM has enough history to adapt.
#' @param adapt_start Iteration at which AM is first allowed to replace `S_0`
#'   with the empirical covariance estimate built from past draws.
#' @param epsilon Small diagonal term in the AM update
#'   `S_n = (1 / n) sum_i (theta^(i) - theta_bar)(theta^(i) - theta_bar)^T + epsilon I`.
#' @param regularization Deprecated compatibility alias for `epsilon`.
#'
#' @return An object of class `"adaptive_mcmc_run"`.
#'
#' @examples
#' target <- make_correlated_t_target()
#' run <- adaptive_metropolis(
#'   target_density = target$density,
#'   initial_state = target$recommended_initial,
#'   n_iter = 300,
#'   initial_proposal_covariance = diag(2),
#'   adapt_start = 50
#' )
#' tail(run$adaptation_magnitude)
#'
#' @export
adaptive_metropolis <- function(target_density = NULL,
                                initial_state,
                                n_iter,
                                initial_proposal_covariance = diag(length(initial_state)),
                                adapt_start = 50L,
                                epsilon = 1e-8,
                                regularization = NULL,
                                log_target = NULL) {
  # Validate the R inputs before calling the compiled sampler.
  target_density <- resolve_target_density(target_density, log_target)
  initial_state <- ensure_numeric_state(initial_state)
  n_iter <- ensure_positive_integer(n_iter, "n_iter")
  initial_proposal_covariance <- ensure_square_matrix(
    initial_proposal_covariance,
    length(initial_state),
    "initial_proposal_covariance"
  )
  adapt_start <- ensure_positive_integer(adapt_start, "adapt_start")
  if (!is.null(regularization)) {
    epsilon <- regularization
  }

  epsilon <- ensure_positive_number(epsilon, "epsilon")

  if (adapt_start > n_iter) {
    stop("`adapt_start` must not be larger than `n_iter`.", call. = FALSE)
  }

  check_initial_density(target_density, initial_state)

  # Call the compiled implementation in src/adaptive_metropolis.cpp.
  result <- adaptive_metropolis_cpp(
    target_density = target_density,
    initial_state = initial_state,
    n_iter = n_iter,
    initial_proposal_covariance = initial_proposal_covariance,
    adapt_start = adapt_start,
    epsilon = epsilon
  )

  # Add the standard class and metadata expected by the R tools.
  standardise_sampler_output(result, initial_state = initial_state)
}

#' Run Robust Adaptive Metropolis
#'
#' Robust Adaptive Metropolis (RAM) adjusts its proposal using local acceptance
#' feedback rather than a full empirical covariance estimate. The R wrapper
#' checks the inputs, calls `robust_adaptive_metropolis_cpp()`, and returns the
#' result in the standard package format.
#'
#' @param target_density Function of one numeric state vector `x` that returns
#'   the target density `pi(x)`.
#' @param log_target Deprecated compatibility alias. If supplied, the wrapper
#'   converts `log_target(x)` to `exp(log_target(x))`.
#' @param initial_state Numeric vector giving the starting value of the chain.
#' @param n_iter Number of Metropolis updates to run.
#' @param initial_proposal_covariance Initial covariance matrix used to build
#'   the RAM proposal factor.
#' @param target_acceptance Target acceptance rate `alpha^*` that RAM tries to
#'   track over time.
#' @param adapt_exponent Exponent in the learning-rate schedule
#'   `eta_n = n^{-adapt_exponent}`. Larger values make the adaptation shrink
#'   faster.
#'
#' @return An object of class `"adaptive_mcmc_run"`.
#'
#' @examples
#' target <- make_high_dimensional_gaussian_target(dimension = 4)
#' run <- robust_adaptive_metropolis(
#'   target_density = target$density,
#'   initial_state = target$recommended_initial,
#'   n_iter = 300,
#'   initial_proposal_covariance = target$recommended_proposal_covariance
#' )
#' range(run$adaptation_magnitude)
#'
#' @export
robust_adaptive_metropolis <- function(target_density = NULL,
                                       initial_state,
                                       n_iter,
                                       initial_proposal_covariance = diag(length(initial_state)),
                                       target_acceptance = 0.234,
                                       adapt_exponent = 0.67,
                                       log_target = NULL) {
  # Validate the R inputs before calling the compiled sampler.
  target_density <- resolve_target_density(target_density, log_target)
  initial_state <- ensure_numeric_state(initial_state)
  n_iter <- ensure_positive_integer(n_iter, "n_iter")
  initial_proposal_covariance <- ensure_square_matrix(
    initial_proposal_covariance,
    length(initial_state),
    "initial_proposal_covariance"
  )
  target_acceptance <- ensure_probability(target_acceptance, "target_acceptance")
  adapt_exponent <- ensure_positive_number(adapt_exponent, "adapt_exponent")

  check_initial_density(target_density, initial_state)

  # Call the compiled implementation in src/robust_adaptive_metropolis.cpp.
  result <- robust_adaptive_metropolis_cpp(
    target_density = target_density,
    initial_state = initial_state,
    n_iter = n_iter,
    initial_proposal_covariance = initial_proposal_covariance,
    target_acceptance = target_acceptance,
    adapt_exponent = adapt_exponent
  )

  # Add the standard class and metadata expected by the R tools.
  standardise_sampler_output(result, initial_state = initial_state)
}

#' Run Delayed Rejection Adaptive Metropolis
#'
#' DRAM combines AM-style covariance learning with a smaller second-stage
#' proposal used after a first-stage rejection. The R wrapper checks the
#' inputs, calls `dram_cpp()`, and returns the result in the standard package
#' format.
#'
#' @param target_density Function of one numeric state vector `x` that returns
#'   the target density `pi(x)`.
#' @param log_target Deprecated compatibility alias. If supplied, the wrapper
#'   converts `log_target(x)` to `exp(log_target(x))`.
#' @param initial_state Numeric vector giving the starting value of the chain.
#' @param n_iter Number of Metropolis updates to run.
#' @param initial_proposal_covariance Initial covariance matrix for the
#'   first-stage proposal.
#' @param adapt_start Iteration at which AM-style covariance learning is first
#'   allowed to update the proposal.
#' @param delayed_rejection_scale Number `gamma` in `(0, 1]` that shrinks the
#'   first-stage covariance for the second-stage rescue proposal.
#' @param epsilon Small diagonal term in the AM-style update
#'   `S_n = (1 / n) sum_i (theta^(i) - theta_bar)(theta^(i) - theta_bar)^T + epsilon I`.
#' @param regularization Deprecated compatibility alias for `epsilon`.
#'
#' @return An object of class `"adaptive_mcmc_run"`.
#'
#' @examples
#' target <- make_dram_rescue_target()
#' run <- dram(
#'   target_density = target$density,
#'   initial_state = target$recommended_initial,
#'   n_iter = 300,
#'   initial_proposal_covariance = target$recommended_proposal_covariance,
#'   delayed_rejection_scale = target$recommended_delayed_rejection_scale
#' )
#' mean(run$second_stage_attempted)
#'
#' @export
dram <- function(target_density = NULL,
                 initial_state,
                 n_iter,
                 initial_proposal_covariance = diag(length(initial_state)),
                 adapt_start = 50L,
                 delayed_rejection_scale = 0.5,
                 epsilon = 1e-8,
                 regularization = NULL,
                 log_target = NULL) {
  # Validate the R inputs before calling the compiled sampler.
  target_density <- resolve_target_density(target_density, log_target)
  initial_state <- ensure_numeric_state(initial_state)
  n_iter <- ensure_positive_integer(n_iter, "n_iter")
  initial_proposal_covariance <- ensure_square_matrix(
    initial_proposal_covariance,
    length(initial_state),
    "initial_proposal_covariance"
  )
  adapt_start <- ensure_positive_integer(adapt_start, "adapt_start")
  delayed_rejection_scale <- ensure_positive_number(
    delayed_rejection_scale,
    "delayed_rejection_scale"
  )
  if (!is.null(regularization)) {
    epsilon <- regularization
  }

  epsilon <- ensure_positive_number(epsilon, "epsilon")

  if (adapt_start > n_iter) {
    stop("`adapt_start` must not be larger than `n_iter`.", call. = FALSE)
  }

  check_initial_density(target_density, initial_state)

  # Call the compiled implementation in src/dram.cpp.
  result <- dram_cpp(
    target_density = target_density,
    initial_state = initial_state,
    n_iter = n_iter,
    initial_proposal_covariance = initial_proposal_covariance,
    adapt_start = adapt_start,
    delayed_rejection_scale = delayed_rejection_scale,
    epsilon = epsilon
  )

  # Add the standard class and metadata expected by the R tools.
  standardise_sampler_output(result, initial_state = initial_state)
}

